'use strict';
/**
 * 从 catalog schema 生成「机械参数校验」（N2.1 第三段的第一步：**只读比对，不替换**）
 *
 * 产出 `src/agent/tool-validate.generated.js`：把 schema 里能表达的东西翻译成校验规则
 *   - `required`                 → 缺字段报 MISSING_ARG / MISSING_PATH / MISSING_CONTENT（按字段名归口）
 *   - `type`                     → 类型不符报 INVALID_ARG
 *   - `enum`                     → 取值不在集合里报 INVALID_ARG
 *   - `minimum` / `maximum`       → 越界报 INVALID_ARG
 *
 * **这一步不改行为**：手写 `tool-validate.js` 仍是唯一生效实现。生成的这份只被
 * `test/unit/tool-args-dualrun.test.cjs` 拿去与手写逐条比对 —— 比对结果（一致 / 谁更严 / 谁更松 /
 * 只差错误码）就是「还差哪些 schema」的清单，见 docs/TOOL-VALIDATE-DUALRUN.md。
 *
 * 用法：
 *   node scripts/generate-tool-validators.cjs           # 重新生成
 *   node scripts/generate-tool-validators.cjs --check    # 生成物是否过期
 */
const fs = require('node:fs');
const path = require('node:path');

const ROOT = path.join(__dirname, '..');
const OUT = path.join(ROOT, 'src', 'agent', 'tool-validate.generated.js');

/** 路径类字段缺了报 MISSING_PATH、内容类报 MISSING_CONTENT，其余 MISSING_ARG。 */
function missingCodeFor(field) {
  const f = String(field || '').toLowerCase();
  if (f.includes('path') || f === 'dir' || f === 'file') return 'MISSING_PATH';
  if (f === 'content' || f === 'text' || f === 'body') return 'MISSING_CONTENT';
  return 'MISSING_ARG';
}

const TYPE_CHECKS = new Set(['string', 'number', 'boolean', 'array', 'object']);

function buildRules() {
  const catalog = require(path.join(ROOT, 'src', 'agent', 'tool-catalog'));
  // 用全集（静态 + 条件注入）：`goal_*` 的 schema 齐全，只是不在静态表里。
  const tools = Array.isArray(catalog.ALL_KNOWN_TOOLS)
    ? catalog.ALL_KNOWN_TOOLS
    : Array.isArray(catalog.ALL_STATIC_TOOLS)
      ? catalog.ALL_STATIC_TOOLS
      : [];
  const rules = {};
  for (const tool of tools) {
    const fn = tool && tool.function ? tool.function : null;
    const name = fn && fn.name;
    if (!name) continue;
    const params = (fn && fn.parameters) || {};
    const props = params.properties && typeof params.properties === 'object' ? params.properties : {};
    const required = Array.isArray(params.required) ? params.required.filter((f) => typeof f === 'string') : [];
    const checks = [];
    for (const [field, spec] of Object.entries(props)) {
      if (!spec || typeof spec !== 'object') continue;
      if (spec.type && TYPE_CHECKS.has(spec.type)) {
        checks.push({ kind: 'type', field, type: spec.type });
      }
      if (Array.isArray(spec.enum) && spec.enum.length) {
        checks.push({ kind: 'enum', field, values: spec.enum.slice() });
      }
      if (typeof spec.minimum === 'number' || typeof spec.maximum === 'number') {
        checks.push({
          kind: 'range',
          field,
          min: typeof spec.minimum === 'number' ? spec.minimum : null,
          max: typeof spec.maximum === 'number' ? spec.maximum : null
        });
      }
    }
    // 条件规则（allOf / if-then / anyOf）原样搬进规则：求值交给 src/agent/schema-rules.js
    // （手写校验器用同一个求值器，两边口径必然一致）。
    const allOf = Array.isArray(params.allOf) ? params.allOf : null;
    const anyOf = Array.isArray(params.anyOf) ? params.anyOf : null;
    if (required.length || checks.length || allOf || anyOf) {
      const rule = { required, checks };
      if (allOf) rule.allOf = allOf;
      if (anyOf) rule.anyOf = anyOf;
      rules[name] = rule;
    }
  }
  return rules;
}

function render(rules) {
  const head = [
    '// AUTO-GENERATED by scripts/generate-tool-validators.cjs — DO NOT EDIT.',
    '// 更新：npm run generate:tool-validators；校验：npm run verify:tool-validators。',
    '//',
    '// **这份目前不生效**：手写 `tool-validate.js` 仍是唯一实现。它只被双跑用例拿去比对，',
    '// 用来回答「schema 到底能表达多少校验」（见 docs/TOOL-VALIDATE-DUALRUN.md）。',
    "'use strict';",
    ''
  ].join('\n');

  const body = `
/** @type {Record<string, { required: string[], checks: Array<any> }>} */
const RULES = ${JSON.stringify(rules, null, 2)};

/** 允许空串的字段（内容类）：见 \`blankIsMissing\` 的注释。 */
const BLANK_OK = new Set(['content', 'text', 'body', 'patch', 'diff', 'command', 'note']);

const { evaluateRules } = require('./schema-rules');

function typeOk(val, type) {
  if (type === 'array') return Array.isArray(val);
  if (type === 'object') return !!val && typeof val === 'object' && !Array.isArray(val);
  if (type === 'number') return typeof val === 'number' && Number.isFinite(val);
  return typeof val === type;
}

function missingCodeFor(field) {
  const f = String(field || '').toLowerCase();
  if (f.includes('path') || f === 'dir' || f === 'file') return 'MISSING_PATH';
  if (f === 'content' || f === 'text' || f === 'body') return 'MISSING_CONTENT';
  return 'MISSING_ARG';
}

/**
 * 只做 schema 能表达的机械校验。返回形状与手写实现一致：\`{ ok, error?, errorCode?, retryable? }\`。
 *
 * @param {string} name
 * @param {any} args
 */
function validateToolArgsGenerated(name, args) {
  const rules = RULES[String(name || '').trim()];
  if (!rules) return { ok: true };
  const a = args && typeof args === 'object' ? args : {};

  for (const field of rules.required) {
    const v = a[field];
    // 空白字符串算不算「缺失」：标识类字段（path / query / pattern / name …）算，
    // **内容类不算** —— 例如 fs_write_file 的 content: "" 是「把文件清空」的合法调用。
    const blankIsMissing = !BLANK_OK.has(String(field).toLowerCase());
    const absent = v === undefined || v === null || (blankIsMissing && typeof v === 'string' && !v.trim());
    if (absent) {
      return {
        ok: false,
        error: \`\${name} 缺少 \${field}\`,
        errorCode: missingCodeFor(field),
        retryable: false
      };
    }
  }

  for (const check of rules.checks) {
    const v = a[check.field];
    if (v === undefined || v === null) continue;
    if (check.kind === 'type' && !typeOk(v, check.type)) {
      return {
        ok: false,
        error: \`\${name} 的 \${check.field} 应该是 \${check.type}\`,
        errorCode: 'INVALID_ARG',
        retryable: false
      };
    }
    if (check.kind === 'enum' && !check.values.includes(v)) {
      return {
        ok: false,
        error: \`\${name} 的 \${check.field} 必须是 \${check.values.join(' / ')}（收到「\${v}」）\`,
        errorCode: 'INVALID_ARG',
        retryable: false
      };
    }
    if (check.kind === 'range') {
      const n = Number(v);
      if (!Number.isFinite(n) || (check.min !== null && n < check.min) || (check.max !== null && n > check.max)) {
        return {
          ok: false,
          error: \`\${name} 的 \${check.field} 超出范围（\${v}）\`,
          errorCode: 'INVALID_ARG',
          retryable: true
        };
      }
    }
  }
  // 条件规则（allOf / if-then / anyOf）最后求值：与手写校验器同一份实现，口径不会分叉。
  if ((Array.isArray(rules.allOf) && rules.allOf.length) || (Array.isArray(rules.anyOf) && rules.anyOf.length)) {
    return evaluateRules(name, { allOf: rules.allOf || [], anyOf: rules.anyOf || [] }, a);
  }
  return { ok: true };
}

module.exports = { RULES, validateToolArgsGenerated, missingCodeFor };
`;

  return head + body;
}

/**
 * 双跑报告（`--report`）：差异分类计数 + 逐条清单 + 「还差哪些 schema」。
 * 数据来自 `scripts/lib/tool-validate-dualrun.cjs`（与测试同一份单一来源）。
 */
function writeReport() {
  const { summarize } = require(path.join(ROOT, 'scripts', 'lib', 'tool-validate-dualrun.cjs'));
  const { total, agree, diffs, byCategory } = summarize();
  const order = [
    ['schema-empty', 'schema 里没有这个字段/规则（先在 catalog 补字段，生成器才有的可生成）'],
    ['schema-conditional', '要在某个 action 下才必填（要么 schema 支持 if/then，要么生成器显式列条件）'],
    ['schema-lacks-enum', '手写有取值集合，schema 没写 enum'],
    ['schema-lacks-range', '手写有上下限，schema 没写 minimum/maximum'],
    ['alias', '手写接受别名（一个字段多个名字），schema 声明不了'],
    ['errorCode-taxonomy', '两边都拒绝，只是错误码归类不同（口径问题，不是行为问题）'],
    ['handwritten-missing-enum', 'schema 有 enum 而手写没校验（旧代码漏了）']
  ];
  const md = [];
  md.push('# 工具校验：手写 vs 生成 双跑报告');
  md.push('');
  md.push('> **AUTO-GENERATED** by `npm run report:tool-validators`（数据源 `scripts/lib/tool-validate-dualrun.cjs`）。');
  md.push('> 生成的 `src/agent/tool-validate.generated.js` **还没生效**：手写 `tool-validate.js` 仍是唯一实现。');
  md.push('> 这份报告回答的是「schema 到底能表达多少校验」以及「还差什么才能替换」。');
  md.push('');
  md.push(`**一致 ${agree}/${total} 条（${Math.round((agree / total) * 100)}%），差异 ${diffs.length} 条。**`);
  md.push('');
  md.push('| 分类 | 条数 | 含义 |');
  md.push('|---|---|---|');
  for (const [key, desc] of order) {
    md.push(`| \`${key}\` | ${byCategory[key] || 0} | ${desc} |`);
  }
  md.push('');
  md.push('## 逐条差异');
  md.push('');
  md.push('| 工具 | 用例 | 手写 | 生成 | 分类 |');
  md.push('|---|---|---|---|---|');
  for (const d of diffs) {
    md.push(`| \`${d.tool}\` | ${d.why} | ${d.hand} | ${d.gen} | \`${d.category}\` |`);
  }
  md.push('');
  md.push('## 结论：要替换手写校验，先补这四件事');
  md.push('');
  md.push('1. **`goal_*` / `plan_create` / `host_proc` / `read_symbol` 的 schema 是空的或只有类型** —— ');
  md.push('   跨字段规则（「objective / todos / checks 至少一个」「filePath+name 或 filePath+line」）schema 目前表达不了；');
  md.push('2. **条件必填 6 处**（`lsp` 的 operation 分支、`worktree` 的 create/remove、`host_proc kill`）：');
  md.push('   要在 catalog 里写 `if/then`，或在生成器里显式列「action → 必填字段」表 —— 二选一；');
  md.push('3. **别名**（`grep.query` / `glob.glob` / `fs_read_file.dirPath`）：');
  md.push('   schema 只能声明一个字段名，要么删别名（改调用方），要么在生成器里加 `aliases` 映射（并接受它是第二来源）；');
  md.push('4. ~~**`lsp.operation` 的 enum、`web_search.fetchTop/page` 的 min/max 补进 schema**~~ —— ');
  md.push('   **已完成（2026-11-18）**：手写改成从 schema 读（`toolActionEnum(name, field)` / `numericBounds(name, field)`），');
  md.push('   数字只有一份；`schema-lacks-enum` 与 `schema-lacks-range` 两类归零，一致率 35 → 37。');
  md.push('');
  const out = path.join(ROOT, 'docs', 'TOOL-VALIDATE-DUALRUN.md');
  fs.writeFileSync(out, `${md.join('\n')}\n`, 'utf8');
  console.log(`[dieyun:tool-validate] wrote ${path.relative(ROOT, out)}（一致 ${agree}/${total}，差异 ${diffs.length}）`);
}

function main() {
  if (process.argv.includes('--report')) {
    writeReport();
    return;
  }
  const check = process.argv.includes('--check');
  const rules = buildRules();
  const text = render(rules);
  if (check) {
    const committed = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8').replace(/\r\n/g, '\n') : '';
    if (committed.trim() !== text.trim()) {
      console.error(`✗ ${path.relative(ROOT, OUT)} 过期：跑 npm run generate:tool-validators`);
      process.exit(1);
    }
    console.log(`[dieyun:tool-validate] OK（${Object.keys(rules).length} 个工具）`);
    return;
  }
  fs.writeFileSync(OUT, text, 'utf8');
  const withRequired = Object.values(rules).filter((r) => r.required.length).length;
  const withChecks = Object.values(rules).filter((r) => r.checks.length).length;
  console.log(
    `[dieyun:tool-validate] wrote ${path.relative(ROOT, OUT)}（${Object.keys(rules).length} 个工具有机械规则：required ${withRequired} / 类型·枚举·范围 ${withChecks}）`
  );
}

main();
