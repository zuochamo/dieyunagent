'use strict';

/**
 * Generate docs/rpc-catalog.json + docs/rpc-catalog.md from Gateway + Rust RPC registrations.
 * Usage:
 *   node scripts/generate-rpc-catalog.cjs
 *   node scripts/generate-rpc-catalog.cjs --check   # fail if committed catalog is stale
 */

const fs = require('fs');
const path = require('path');
const {
  collectGatewayMethods,
  collectRustMethods,
  collectNodeInvokedMethods,
  mergeCatalog,
  groupByNamespace
} = require('./lib/extract-rpc-methods.cjs');

const ROOT = path.join(__dirname, '..');
const JSON_OUT = path.join(ROOT, 'docs', 'rpc-catalog.json');
const MD_OUT = path.join(ROOT, 'docs', 'rpc-catalog.md');
const TS_OUT = path.join(ROOT, 'types', 'core-rpc.d.ts');

function buildCatalog() {
  const gatewayMap = collectGatewayMethods(ROOT);
  const rustMap = collectRustMethods(ROOT);
  const methods = mergeCatalog(gatewayMap, rustMap);
  return {
    version: 1,
    generatedAt: new Date().toISOString(),
    description: 'Auto-generated RPC method index for dieyunagent Gateway + dieyun-core',
    stats: {
      total: methods.length,
      gatewayOnly: methods.filter((m) => m.layer === 'gateway').length,
      rustOnly: methods.filter((m) => m.layer === 'rust').length,
      both: methods.filter((m) => m.layer === 'both').length
    },
    methods
  };
}

/**
 * Node 侧「真的会发出去」的方法名，catalog 里必须能找到实现（rust 或 gateway）。
 *
 * 这条闸门抓的是一类静默事故：宿主调一个已被删除的方法 → core 回 `UNKNOWN_METHOD` →
 * 调用点 `catch {}` 吞掉 → 功能看起来「点了没反应」。历史案例：`agent.loop.cancel`
 * 在 Rust 侧删除后，主进程的停止路径还在调它（见 rpc 审计 F1）。
 *
 * @returns {{ method: string, sources: string[] }[]}
 */
function findUnimplementedInvokedMethods(catalog) {
  const known = new Set(catalog.methods.map((m) => m.method));
  const invoked = collectNodeInvokedMethods(ROOT);
  const out = [];
  for (const [method, files] of invoked) {
    if (!known.has(method)) out.push({ method, sources: [...files].sort() });
  }
  return out.sort((a, b) => a.method.localeCompare(b.method));
}

function renderTypes(catalog) {
  const coreMethods = catalog.methods.filter((m) => m.layer !== 'gateway').map((m) => m.method);
  const gatewayOnly = catalog.methods.filter((m) => m.layer === 'gateway').map((m) => m.method);
  const union = (names) =>
    names.length ? names.map((n) => `  | '${n}'`).join('\n') : '  never';

  const layerLines = catalog.methods
    .map((m) => `  '${m.method}': '${m.layer}';`)
    .join('\n');

  return `// AUTO-GENERATED by scripts/generate-rpc-catalog.cjs — DO NOT EDIT.
// 更新：npm run generate:rpc-catalog；校验：npm run verify:rpc-catalog。
//
// 用途：方法名只能从这张表里取。参数 / 返回字段的强类型要等 core 侧的分派表带上参数
// schema（docs/RUST-CORE-REFACTOR-PLAN.md P1 · R1）之后再生成 —— 那之前，这里至少能挡住
// 「调了一个不存在的方法」这类运行期 UNKNOWN_METHOD。

/** core（Rust）实现了的方法。 */
export type CoreRpcMethod =
${union(coreMethods)};

/** 只有 Gateway 实现的方法。 */
export type GatewayOnlyRpcMethod =
${union(gatewayOnly)};

export type RpcMethod = CoreRpcMethod | GatewayOnlyRpcMethod;

export type RpcLayer = 'gateway' | 'rust' | 'both';

/** 方法 → 实现层。 */
export type RpcLayerMap = {
${layerLines}
};
`;
}

function writeOutputs(catalog) {
  const jsonText = `${JSON.stringify(catalog, null, 2)}\n`;
  const mdText = renderMarkdown(catalog);
  const tsText = renderTypes(catalog);
  return { jsonText, mdText, tsText };
}

function normalizeJson(obj) {
  return `${JSON.stringify(obj, null, 2)}\n`;
}

function main() {
  const check = process.argv.includes('--check');
  const catalog = buildCatalog();
  const { jsonText, mdText, tsText } = writeOutputs(catalog);
  const unimplemented = findUnimplementedInvokedMethods(catalog);

  if (check) {
    // git autocrlf 会把检出文件落成 CRLF，而生成物恒为 LF；只按行尾不同就判 stale 会假红。
    // "--check" 的语义是「目录内容是否过期」，比较前统一归一行尾。
    const normalizeEol = (text) => String(text).replace(/\r\n?/g, '\n');
    const existingJson = normalizeEol(fs.existsSync(JSON_OUT) ? fs.readFileSync(JSON_OUT, 'utf8') : '');
    const existingMd = normalizeEol(fs.existsSync(MD_OUT) ? fs.readFileSync(MD_OUT, 'utf8') : '');
    const existingTs = normalizeEol(fs.existsSync(TS_OUT) ? fs.readFileSync(TS_OUT, 'utf8') : '');
    const stripStamp = (text) => text.replace(/"generatedAt": "[^"]+"/, '"generatedAt": "…"');
    const jsonOk = stripStamp(existingJson) === stripStamp(jsonText);
    const mdOk =
      existingMd.replace(/生成时间：[^\n]+/, '生成时间：…') ===
      mdText.replace(/生成时间：[^\n]+/, '生成时间：…');
    const tsOk = existingTs === normalizeEol(tsText);
    if (!jsonOk || !mdOk || !tsOk) {
      console.error('[dieyun:rpc] catalog is stale — run: npm run generate:rpc-catalog');
      process.exit(1);
    }
    if (unimplemented.length) {
      console.error('[dieyun:rpc] 以下方法在 Node 侧被调用，但 catalog 里没有实现：');
      for (const row of unimplemented) {
        console.error(`  - ${row.method}  ← ${row.sources.join(', ')}`);
      }
      console.error('  删掉调用点，或补上实现（不许让它静默 UNKNOWN_METHOD）。');
      process.exit(1);
    }
    console.log('[dieyun:rpc] catalog OK');
    return;
  }

  fs.mkdirSync(path.dirname(JSON_OUT), { recursive: true });
  fs.writeFileSync(JSON_OUT, jsonText, 'utf8');
  fs.writeFileSync(MD_OUT, mdText, 'utf8');
  fs.mkdirSync(path.dirname(TS_OUT), { recursive: true });
  fs.writeFileSync(TS_OUT, tsText, 'utf8');
  console.log(`[dieyun:rpc] wrote ${path.relative(ROOT, JSON_OUT)} (${catalog.stats.total} methods)`);
  console.log(`[dieyun:rpc] wrote ${path.relative(ROOT, MD_OUT)}`);
  console.log(`[dieyun:rpc] wrote ${path.relative(ROOT, TS_OUT)}`);
  if (unimplemented.length) {
    console.error('[dieyun:rpc] 警告：以下方法被 Node 调用但 catalog 里没有实现：');
    for (const row of unimplemented) console.error(`  - ${row.method} ← ${row.sources.join(', ')}`);
  }
}

void normalizeJson;
main();

function renderMarkdown(catalog) {
  const lines = [
    '# RPC Catalog（自动生成）',
    '',
    '> 勿手改。更新 RPC 注册后运行 `npm run generate:rpc-catalog`，CI 用 `npm run verify:rpc-catalog` 校验。',
    '',
    `生成时间：${catalog.generatedAt}`,
    '',
    '| 统计 | 数量 |',
    '|------|------|',
    `| 总计 | ${catalog.stats.total} |`,
    `| Gateway only | ${catalog.stats.gatewayOnly} |`,
    `| Rust only | ${catalog.stats.rustOnly} |`,
    `| Both | ${catalog.stats.both} |`,
    '',
    '## 按命名空间',
    ''
  ];

  for (const [ns, rows] of groupByNamespace(catalog.methods)) {
    lines.push(`### ${ns} (${rows.length})`);
    lines.push('');
    lines.push('| Method | Layer | Gateway source | Rust |');
    lines.push('|--------|-------|----------------|------|');
    for (const row of rows) {
      lines.push(
        `| \`${row.method}\` | ${row.layer} | ${row.gateway.join(', ') || '—'} | ${row.rust.length ? 'yes' : '—'} |`
      );
    }
    lines.push('');
  }
  return `${lines.join('\n')}\n`;
}
