  /** 鱼：按弧长把 count 个点分给各条轮廓（每段至少 2 点，眼睛和小鳍也看得见） */
  function fishPoints(count, slab) {
    const pts = new Float32Array(count * 3);
    const cursor = { i: 0 };
    const rand = mulberry32(0xf15);
    const z = () => (rand() - 0.5) * 2 * slab;
    const pieces = FISH_PIECES.map((p) => ({ pts: p, len: polyLen(p) }));
    const n = allocByWeight(
      count,
      pieces.map((p) => p.len)
    );
    for (let i = 0; i < n.length; i++) {
      if (n[i] >= 2) continue;
      let maxIdx = 0;
      for (let j = 1; j < n.length; j++) if (n[j] > n[maxIdx]) maxIdx = j;
      const need = 2 - n[i];
      n[maxIdx] -= need;
      n[i] += need;
    }
    pieces.forEach((piece, i) => {
      const seg = sampleByArc(piece.pts, n[i]);
      for (let k = 0; k < seg.length; k++) pushPoint(pts, cursor, seg[k][0], seg[k][1], z());
    });
    // 包围盒居中 + 最长半轴归一到 1（与 question 同口径）
    let minX = Infinity,
      maxX = -Infinity,
      minY = Infinity,
      maxY = -Infinity;
    for (let i = 0; i < count; i++) {
      const x = pts[i * 3];
      const y = pts[i * 3 + 1];
      if (x < minX) minX = x;
      if (x > maxX) maxX = x;
      if (y < minY) minY = y;
      if (y > maxY) maxY = y;
    }
    const cx = (minX + maxX) / 2;
    const cy = (minY + maxY) / 2;
    const scale = 1 / Math.max((maxX - minX) / 2, (maxY - minY) / 2, 1e-6);
    for (let i = 0; i < count; i++) {
      pts[i * 3] = (pts[i * 3] - cx) * scale;
      pts[i * 3 + 1] = (pts[i * 3 + 1] - cy) * scale;
    }
    return pts;
  }

