'use strict';

function psQuote(value) {
  return `'${String(value).replace(/'/g, "''")}'`;
}

/**
 * 生成独立 PowerShell 安装脚本：等待引导进程退出后静默安装，并显示 WinForms 进度窗。
 */
function buildInstallRunnerScript(opts) {
  const installerPath = opts.installerPath || '';
  const progressFile = opts.progressFile || '';
  const installLogFile = progressFile.replace(/dieyun-update-progress\.json$/i, 'dieyun-install-runner.log');
  const bootstrapPid = Number(opts.bootstrapPid) || 0;
  const targetExeName = opts.targetExeName || 'dieyunagent.exe';
  const exeNameNoExt = targetExeName.replace(/\.exe$/i, '');
  const targetVersion = opts.targetVersion || '';
  const fromVersion = opts.fromVersion || '';

  return [
    '$ErrorActionPreference = "Stop"',
    'Add-Type -AssemblyName System.Windows.Forms',
    'Add-Type -AssemblyName System.Drawing',
    '[Console]::OutputEncoding = [System.Text.Encoding]::UTF8',
    `$Installer = ${psQuote(installerPath)}`,
    `$ProgressFile = ${psQuote(progressFile)}`,
    `$LogFile = ${psQuote(installLogFile)}`,
    `$BootstrapPid = ${bootstrapPid}`,
    `$ExeNameNoExt = ${psQuote(exeNameNoExt)}`,
    `$TargetVersion = ${psQuote(targetVersion)}`,
    `$FromVersion = ${psQuote(fromVersion)}`,
    '',
    'Add-Type @"',
    'using System;',
    'using System.Runtime.InteropServices;',
    'public class DieyunUpdateWin32 {',
    '  [DllImport("user32.dll")] public static extern bool ReleaseCapture();',
    '  [DllImport("user32.dll")] public static extern IntPtr SendMessage(IntPtr hWnd, int msg, int wParam, int lParam);',
    '  public const int WM_NCLBUTTONDOWN = 0xA1;',
    '  public const int HTCAPTION = 0x2;',
    '}',
    '"@',
    '',
    'function Log-Line([string]$Message) {',
    '  try { Add-Content -LiteralPath $LogFile -Encoding UTF8 -Value ("[{0}] {1}" -f (Get-Date -Format "yyyy-MM-dd HH:mm:ss"), $Message) } catch {}',
    '}',
    '',
    'function Set-Progress([int]$Percent, [string]$Message) {',
    '  $payload = (@{ percent = $Percent; message = $Message } | ConvertTo-Json -Compress)',
    '  $utf8 = New-Object System.Text.UTF8Encoding $true',
    '  [System.IO.File]::WriteAllText($ProgressFile, $payload, $utf8)',
    '}',
    '',
    'function Decode-ProgressText([byte[]]$bytes) {',
    '  if (-not $bytes -or $bytes.Length -eq 0) { return $null }',
    '  if ($bytes.Length -ge 3 -and $bytes[0] -eq 0xEF -and $bytes[1] -eq 0xBB -and $bytes[2] -eq 0xBF) {',
    '    return [System.Text.Encoding]::UTF8.GetString($bytes, 3, $bytes.Length - 3)',
    '  }',
    '  if ($bytes.Length -ge 2 -and $bytes[0] -eq 0xFF -and $bytes[1] -eq 0xFE) {',
    '    return [System.Text.Encoding]::Unicode.GetString($bytes)',
    '  }',
    '  if ($bytes.Length -ge 2 -and $bytes[0] -eq 0xFE -and $bytes[1] -eq 0xFF) {',
    '    return [System.Text.Encoding]::BigEndianUnicode.GetString($bytes)',
    '  }',
    '  # 旧版 NSIS：UTF-16 LE 无 BOM',
    '  if (($bytes.Length % 2) -eq 0 -and $bytes.Length -ge 2) {',
    '    $utf16 = [System.Text.Encoding]::Unicode.GetString($bytes)',
    '    if ($utf16 -and $utf16.Trim().StartsWith("{")) { return $utf16 }',
    '  }',
    '  return [System.Text.Encoding]::UTF8.GetString($bytes)',
    '}',
    '',
    'function Read-ProgressPayload {',
    '  if (-not (Test-Path -LiteralPath $ProgressFile)) { return $null }',
    '  try {',
    '    $bytes = [System.IO.File]::ReadAllBytes($ProgressFile)',
    '    $raw = Decode-ProgressText $bytes',
    '    if (-not $raw) { return $null }',
    '    return ($raw.Trim() | ConvertFrom-Json)',
    '  } catch {',
    '    return $null',
    '  }',
    '}',
    '',
    'function Is-ProcessAlive([int]$ProcessId) {',
    '  if ($ProcessId -le 0) { return $false }',
    '  return [bool](Get-Process -Id $ProcessId -ErrorAction SilentlyContinue)',
    '}',
    '',
    'function Kill-AgentProcesses {',
    '  $left = @(Get-Process -Name $ExeNameNoExt -ErrorAction SilentlyContinue)',
    '  foreach ($p in $left) {',
    '    try { Stop-Process -Id $p.Id -Force -ErrorAction SilentlyContinue } catch {}',
    '  }',
    '}',
    '',
    'function Register-DragMove($Control, $Form) {',
    '  $Control.Add_MouseDown({',
    '    param($sender, $e)',
    '    if ($e.Button -ne [System.Windows.Forms.MouseButtons]::Left) { return }',
    '    [DieyunUpdateWin32]::ReleaseCapture() | Out-Null',
    '    [DieyunUpdateWin32]::SendMessage($Form.Handle, [DieyunUpdateWin32]::WM_NCLBUTTONDOWN, [DieyunUpdateWin32]::HTCAPTION, 0) | Out-Null',
    '  })',
    '}',
    '',
    '$bg = [System.Drawing.Color]::FromArgb(18, 21, 31)',
    '$barTrack = [System.Drawing.Color]::FromArgb(40, 45, 60)',
    '$accent = [System.Drawing.Color]::FromArgb(93, 200, 255)',
    '$textMain = [System.Drawing.Color]::FromArgb(230, 232, 245)',
    '$textSub = [System.Drawing.Color]::FromArgb(139, 147, 168)',
    '$textBody = [System.Drawing.Color]::FromArgb(197, 202, 214)',
    '$textHint = [System.Drawing.Color]::FromArgb(111, 119, 138)',
    '',
    '$form = New-Object System.Windows.Forms.Form',
    '$form.Text = "叠云 Agent 更新"',
    '$form.Size = New-Object System.Drawing.Size(480, 268)',
    '$form.StartPosition = "CenterScreen"',
    '$form.FormBorderStyle = "None"',
    '$form.MaximizeBox = $false',
    '$form.MinimizeBox = $false',
    '$form.TopMost = $true',
    '$form.BackColor = $bg',
    '$form.ShowInTaskbar = $true',
    '',
    '$header = New-Object System.Windows.Forms.Panel',
    '$header.Size = New-Object System.Drawing.Size(480, 40)',
    '$header.Location = New-Object System.Drawing.Point(0, 0)',
    '$header.BackColor = $bg',
    '',
    '$headerTitle = New-Object System.Windows.Forms.Label',
    '$headerTitle.AutoSize = $false',
    '$headerTitle.Size = New-Object System.Drawing.Size(432, 24)',
    '$headerTitle.Location = New-Object System.Drawing.Point(24, 10)',
    '$headerTitle.ForeColor = $textSub',
    '$headerTitle.Font = New-Object System.Drawing.Font("Microsoft YaHei UI", 9)',
    '$headerTitle.Text = "叠云 Agent 更新"',
    '$header.BackColor = $bg',
    '$header.Controls.Add($headerTitle)',
    '',
    '$title = New-Object System.Windows.Forms.Label',
    '$title.AutoSize = $false',
    '$title.Size = New-Object System.Drawing.Size(432, 28)',
    '$title.Location = New-Object System.Drawing.Point(24, 52)',
    '$title.ForeColor = $textMain',
    '$title.Font = New-Object System.Drawing.Font("Microsoft YaHei UI", 12, [System.Drawing.FontStyle]::Bold)',
    '$title.Text = "正在安装更新"',
    '',
    '$ver = New-Object System.Windows.Forms.Label',
    '$ver.AutoSize = $false',
    '$ver.Size = New-Object System.Drawing.Size(432, 20)',
    '$ver.Location = New-Object System.Drawing.Point(24, 82)',
    '$ver.ForeColor = $textSub',
    '$ver.Font = New-Object System.Drawing.Font("Microsoft YaHei UI", 9)',
    'if ($FromVersion -and $TargetVersion) { $ver.Text = "v$FromVersion -> v$TargetVersion" }',
    'elseif ($TargetVersion) { $ver.Text = "新版本 v$TargetVersion" }',
    '',
    '$msg = New-Object System.Windows.Forms.Label',
    '$msg.AutoSize = $false',
    '$msg.Size = New-Object System.Drawing.Size(432, 40)',
    '$msg.Location = New-Object System.Drawing.Point(24, 108)',
    '$msg.ForeColor = $textBody',
    '$msg.Font = New-Object System.Drawing.Font("Microsoft YaHei UI", 9)',
    '$msg.Text = "准备中..."',
    '',
    '$barBg = New-Object System.Windows.Forms.Panel',
    '$barBg.Size = New-Object System.Drawing.Size(432, 10)',
    '$barBg.Location = New-Object System.Drawing.Point(24, 158)',
    '$barBg.BackColor = $barTrack',
    '',
    '$bar = New-Object System.Windows.Forms.Panel',
    '$bar.Size = New-Object System.Drawing.Size(0, 10)',
    '$bar.Location = New-Object System.Drawing.Point(0, 0)',
    '$bar.BackColor = $accent',
    '$barBg.Controls.Add($bar)',
    '',
    '$pct = New-Object System.Windows.Forms.Label',
    '$pct.AutoSize = $false',
    '$pct.Size = New-Object System.Drawing.Size(432, 20)',
    '$pct.Location = New-Object System.Drawing.Point(24, 174)',
    '$pct.ForeColor = $textSub',
    '$pct.Font = New-Object System.Drawing.Font("Microsoft YaHei UI", 8.5)',
    '$pct.Text = "0%"',
    '',
    '$hint = New-Object System.Windows.Forms.Label',
    '$hint.AutoSize = $false',
    '$hint.Size = New-Object System.Drawing.Size(432, 36)',
    '$hint.Location = New-Object System.Drawing.Point(24, 198)',
    '$hint.ForeColor = $textHint',
    '$hint.Font = New-Object System.Drawing.Font("Microsoft YaHei UI", 8.5)',
    '$hint.Text = "安装过程中请勿关闭此窗口；文件列表请查看安装向导详情区。"',
    '',
    '$form.Controls.AddRange(@($header, $title, $ver, $msg, $barBg, $pct, $hint))',
    'Register-DragMove $header $form',
    'Register-DragMove $headerTitle $form',
    '',
    '$script:State = "wait-bootstrap"',
    '$script:WaitTicks = 0',
    '$script:InstallProc = $null',
    '$script:InstallExitCode = 1',
    '$script:Simulated = 18',
    '',
    '$timer = New-Object System.Windows.Forms.Timer',
    '$timer.Interval = 160',
    '$timer.Add_Tick({',
    '  try {',
    '    $file = Read-ProgressPayload',
    '    if ($script:State -eq "wait-bootstrap") {',
    '      if ((-not (Is-ProcessAlive $BootstrapPid)) -or $script:WaitTicks -ge 80) {',
    '        Set-Progress 12 "正在结束残留进程..."',
    '        Kill-AgentProcesses',
    '        Start-Sleep -Milliseconds 180',
    '        Set-Progress 18 "正在打开安装向导..."',
    '        $script:InstallProc = Start-Process -FilePath $Installer -ArgumentList @("--updated","--force-run") -PassThru',
    '        if (-not $script:InstallProc) {',
    '          Set-Progress 0 "无法启动安装程序"',
    '          $script:InstallExitCode = 99',
    '          $script:State = "failed"',
    '        } else {',
    '          $form.TopMost = $false',
    '          $hint.Text = "安装向导已打开；下方详情区会显示正在释放的文件。"',
    '          $script:State = "installing"',
    '        }',
    '      } else {',
    '        $script:WaitTicks++',
    '        Set-Progress 8 "等待应用退出..."',
    '      }',
    '    } elseif ($script:State -eq "installing") {',
    '      if (-not $script:InstallProc.HasExited) {',
    '        $script:Simulated = [Math]::Min(94, $script:Simulated + 1)',
    '        if (-not $file -or -not $file.message) {',
    '          Set-Progress $script:Simulated "正在释放程序文件..."',
    '        }',
    '      } else {',
    '        $script:InstallExitCode = [int]$script:InstallProc.ExitCode',
    '        if ($script:InstallExitCode -eq 0) {',
    '          Set-Progress 100 "安装完成，正在启动应用..."',
    '          $script:State = "done"',
    '        } else {',
    '          Set-Progress 0 ("安装失败（错误码 " + $script:InstallExitCode + "）")',
    '          $script:State = "failed"',
    '        }',
    '      }',
    '    }',
    '',
    '    if ($file) {',
    '      $p = [int]$file.percent',
    '      if ($p -lt 0) { $p = 0 }',
    '      if ($p -gt 100) { $p = 100 }',
    '      $bar.Width = [int](432 * ($p / 100.0))',
    '      $pct.Text = "$p%"',
    '      if ($file.message) { $msg.Text = [string]$file.message }',
    '      if ($p -ge 100) {',
    '        $title.Text = "安装完成"',
    '        $hint.Text = "应用即将自动启动..."',
    '      }',
    '      if ($p -eq 0 -and $file.message -like "*失败*") {',
    '        $title.Text = "安装失败"',
    '        $title.ForeColor = [System.Drawing.Color]::FromArgb(229, 115, 115)',
    '        $hint.Text = "请关闭此窗口后，手动运行安装包重试。"',
    '      }',
    '    }',
    '',
    '    if ($script:State -eq "done") {',
    '      $timer.Stop()',
    '      Start-Sleep -Milliseconds 1200',
    '      $form.Close()',
    '    }',
    '  } catch {',
    '    Set-Progress 0 $_.Exception.Message',
    '    $title.Text = "安装失败"',
    '    $title.ForeColor = [System.Drawing.Color]::FromArgb(229, 115, 115)',
    '    $hint.Text = "请关闭此窗口后，手动运行安装包重试。"',
    '    $script:InstallExitCode = 98',
    '    $script:State = "failed"',
    '  }',
    '})',
    '',
    '$form.Add_Shown({ $form.Activate(); $timer.Start() })',
    'Log-Line "install runner UI shown"',
    '[void]$form.ShowDialog()',
    'Log-Line ("install runner exit code " + $script:InstallExitCode)',
    'exit $script:InstallExitCode',
    ''
  ].join('\r\n');
}

module.exports = { buildInstallRunnerScript };
